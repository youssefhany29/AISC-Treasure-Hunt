import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root=new URL('../',import.meta.url);
async function walk(dir) {
  const found=[];
  for(const entry of await readdir(new URL(dir,root),{withFileTypes:true})){
    const relative=dir+entry.name;
    if(entry.isDirectory())found.push(...await walk(relative+'/'));
    else found.push('./'+relative);
  }
  return found;
}
const paths=['./','./index.html',...await walk('css/'),...await walk('js/'),...await walk('assets/images/'),...await walk('assets/sounds/')];
await writeFile(new URL('asset-manifest.js',root),`// Generated by scripts/prepare-cache.mjs. Re-run after adding game assets.\nself.CASE_ASSETS = ${JSON.stringify(paths,null,2)};\n`);
console.log(`Prepared offline cache manifest: ${paths.length} local resources at ${fileURLToPath(root)}`);
